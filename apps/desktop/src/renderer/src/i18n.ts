type Language = AppLanguage;
function getValue(language: Language, section: keyof (typeof translations)["zh"], key: string) {
  const table = translations[language][section] as Record<string, string>;
  const fallback = translations.zh[section] as Record<string, string>;
  return table[key] ?? fallback[key] ?? key;
}

export function createTranslator(language: Language) {
  return {
    language,
    common: (key: keyof (typeof translations)["zh"]["common"]) =>
      getValue(language, "common", key),
    startup: (key: keyof (typeof translations)["zh"]["startup"]) =>
      getValue(language, "startup", key),
    chat: (key: keyof (typeof translations)["zh"]["chat"]) =>
      getValue(language, "chat", key),
    manage: (key: keyof (typeof translations)["zh"]["manage"]) =>
      getValue(language, "manage", key),
    extensions: (key: keyof (typeof translations)["zh"]["extensions"]) =>
      getValue(language, "extensions", key),
    dashboard: (key: keyof (typeof translations)["zh"]["dashboard"]) =>
      getValue(language, "dashboard", key),
    settings: (key: keyof (typeof translations)["zh"]["settings"]) =>
      getValue(language, "settings", key),
    profile: (key: keyof (typeof translations)["zh"]["profile"]) =>
      getValue(language, "profile", key),
    command: (key: keyof (typeof translations)["zh"]["commands"]) =>
      getValue(language, "commands", key),
  };
}

export type AppI18n = ReturnType<typeof createTranslator>;

export function resolvePreferredLanguage(): Language {
  if (typeof window !== "undefined") {
    const stored = window.localStorage.getItem("teamaligned_ui_language");
    if (stored === "zh" || stored === "en") {
      return stored;
    }
    if (window.navigator.language.toLowerCase().startsWith("zh")) {
      return "zh";
    }
  }

  return "en";
}
